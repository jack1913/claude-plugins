"""Builders for the adapters (BRAND.md, DESIGN.md) and the per-brand applied skill: text generated from the built DTCG tokens
(assets/tokens/tokens.json), BRAND-STATE.md and FACTS.md. Nothing is invented: a section with no source says so.

Shared by `brand-creator adapters`, `brand-creator applied-skill` and `brand-creator check` (which compares the state hash). Standard
library only. No clock and no random numbers: the same inputs give the same bytes.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

import bookdata
import qa_rules
from _color import wcag_ratio
from _common import EXIT_USAGE, fail, forbidden_terms, read_state

BRAND_FILE = "BRAND.md"
DESIGN_FILE = "DESIGN.md"
SKILL_DIR = ".claude/skills"
GENERATED = "generated by brand-creator from the tokens, BRAND-STATE.md and FACTS.md; edit those, then regenerate"
PRIVATE_LABELS = re.compile(r"(?i)^(contact\b|postal address)")   # personal contact data stays out of files agents read
# BRAND-STATE architecture -> BRAND.md type and architecture. These pairings are brand-creator's reading of the BRAND.md field values, not
# something the format defines: override with --bm-type and --bm-architecture.
BM_MAP = {"standalone": ("master", "independent"), "family-member": ("sub-brand", "endorsed"), "product-in-family": ("product", "endorsed")}
BM_TYPES = ("master", "product", "sub-brand")
BM_ARCHS = ("branded-house", "endorsed", "sub-brand", "independent")


def view(project: Path) -> dict:
    """What the adapters read from BRAND-STATE.md and FACTS.md. A change here makes the adapter report stale; a change to the phase
    or the review URL does not."""
    st = read_state(project)
    d = st.data()
    gates = d.get("gates", {}) or {}
    raw_ed = str(d.get("edition", "") or "").strip()
    raw_ap = str(d.get("approved_edition", "") or "").strip()
    langs = bookdata.parse_langs(d.get("content_languages", ""))
    canon = str(d.get("canonical_direction", "") or "")
    row = next((r for r in st.directions() if r.get("name") == canon), {})
    return {
        "name": str(d.get("name", "") or d.get("slug", "")), "slug": str(d.get("slug", "")), "tier": str(d.get("tier", "quick")),
        "architecture": str(d.get("architecture", "standalone")), "mark_source": str(d.get("mark_source", "")),
        "content_languages": langs, "edition": raw_ed, "approved_edition": raw_ap, "g5": str(gates.get("G5", "") or "").strip(),
        "canonical_direction": canon, "register": row.get("register", ""),
        "rules": [b for b in bookdata.bullets(bookdata.section_lines(st, "Rules (G4)")) if b.lower().startswith("(rule)") and not re.search(r"\(\.\.\.\)", b)],
        "renames": [ln for ln in bookdata.section_lines(st, "Renames") if ln.strip().startswith("|")],
        "forbidden": forbidden_terms(project),
    }


def state_sha(project: Path) -> str:
    v = view(project)
    return hashlib.sha256(json.dumps({"view": v, "facts": bookdata.facts(project)}, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def approval(v: dict) -> tuple[str, str]:
    if v["g5"] and v["edition"] and v["approved_edition"] == v["edition"]:
        m = re.match(r"^(\d{4}-\d{2}-\d{2})\b", v["g5"])
        return "approved", (m.group(1) if m else "")
    return "pending", ""


def public_facts(project: Path) -> list[dict]:
    return [r for r in bookdata.facts(project) if not PRIVATE_LABELS.match(r.get("fact", ""))]


def role(k: str) -> str:
    return k[6:] if k.startswith("color.") else k


def cell(t) -> str:
    return re.sub(r"\s+", " ", str(t)).replace("|", "\\|").strip()


def yq(t) -> str:
    """A YAML scalar (JSON strings are YAML)."""
    return json.dumps(str(t), ensure_ascii=False)


def mode_hex(doc: dict, mode: str, k: str) -> str:
    return doc["modes"][mode][k]["hex"].lower()


def pairs(doc: dict) -> list[dict]:
    out = []
    for p in doc.get("pairs", []):
        m = p.get("modes", {})
        out.append({"fg": p["fg"], "bg": p["bg"], "kind": p.get("kind", ""), "min": p.get("min"), "label": p.get("label") or "",
                    "light": wcag_ratio(m["light"]["fg_hex"], m["light"]["bg_hex"]), "dark": wcag_ratio(m["dark"]["fg_hex"], m["dark"]["bg_hex"])})
    return out


def fonts(doc: dict) -> list[tuple[str, str]]:
    return [(k[5:], str(v)) for k, v in doc.get("other", {}).items() if k.startswith("font.")]


def logo_paths(project: Path) -> list[str]:
    return [p.relative_to(project).as_posix() for p in bookdata.logo_files(project)]


def facts_table(rows: list[dict]) -> list[str]:
    if not rows:
        return ["No owner-confirmed facts are recorded in FACTS.md yet."]
    out = ["| fact | value | source | confirmed |", "|---|---|---|---|"]
    out += [f"| {cell(r.get('fact', ''))} | {cell(r.get('value', ''))} | {cell(r.get('source', ''))} | {cell(r.get('confirmed', ''))} |" for r in rows]
    return out


def colour_table(doc: dict) -> list[str]:
    out = ["| role | light | dark |", "|---|---|---|"]
    for k in sorted(doc["modes"]["light"]):
        dark = mode_hex(doc, "dark", k) if k in doc["modes"]["dark"] else "-"
        out.append(f"| {role(k)} | {mode_hex(doc, 'light', k)} | {dark} |")
    return out


def pair_table(doc: dict) -> list[str]:
    ps = pairs(doc)
    if not ps:
        return ["No contrast pairs are declared in the tokens."]
    out = ["| text or shape | on | kind | target | light | dark |", "|---|---|---|---|---|---|"]
    for p in ps:
        out.append(f"| {role(p['fg'])} | {role(p['bg'])} | {cell(p['kind'])} | {p['min']}:1 | {p['light']:.2f}:1 | {p['dark']:.2f}:1 |")
    return out


# ---------------------------------------------------------------- BRAND.md

def brand_md(project: Path, *, bm_type: str | None = None, bm_arch: str | None = None) -> str:
    v = view(project)
    doc, _ = bookdata.tokens(project)
    mt, ma = BM_MAP.get(v["architecture"], BM_MAP["standalone"])
    mt, ma = bm_type or mt, bm_arch or ma
    if mt not in BM_TYPES:
        fail(EXIT_USAGE, f"--bm-type {mt!r}: one of {', '.join(BM_TYPES)}")
    if ma not in BM_ARCHS:
        fail(EXIT_USAGE, f"--bm-architecture {ma!r}: one of {', '.join(BM_ARCHS)}")
    state, date = approval(v)
    facts = bookdata.facts(project)
    L = ["---", f"type: {mt}", f"architecture: {ma}", f"name: {yq(v['name'])}", f"slug: {yq(v['slug'])}", f"edition: {yq(v['edition'])}",
         f"status: {state}" + (f"  # approved {date}" if date else "")]
    if v["content_languages"]:
        L.append("languages: [" + ", ".join(yq(x) for x in v["content_languages"]) + "]")
    L += ["---", f"<!-- {GENERATED} -->", "", f"# {v['name']}", ""]
    L += ["## Strategy", "",
          f"{v['name']} is a {'standalone brand' if v['architecture'] == 'standalone' else v['architecture'] + ' brand'} (tier {v['tier']}, edition "
          f"{v['edition'] or 'not set'}, {state}{' ' + date if date else ''}). What it says about itself is what the owner confirmed, "
          "one source each; nothing else may be claimed in its name.", ""]
    if v["canonical_direction"]:
        L += [f"Direction: {v['canonical_direction']}" + (f" (register: {v['register']})" if v["register"] else "") + ".", ""]
    if v["architecture"] != "standalone":
        L += ["Family: the profile of the parent brand and what a product never borrows from it are in FAMILY.md.", ""]
    L += ["### Facts", ""] + facts_table(public_facts(project)) + ["", "Contact rows are left out of this file on purpose.", ""]
    voice = [r for r in facts if re.match(r"(?i)^(voice|tone)\b", r.get("fact", ""))]
    L += ["## Voice", ""]
    if voice:
        L += [f"- {r['fact']}: {r.get('value', '')}" for r in voice]
    else:
        L += ["No voice facts are recorded: add rows labelled `voice ...` or `tone ...` to FACTS.md and regenerate. Nothing is invented here."]
    L += [""]
    if v["content_languages"]:
        L += [f"Text language(s): {', '.join(v['content_languages'])}.", ""]
    if v["forbidden"]:
        L += ["Never use (the FORBIDDEN list of the brief and research/cliches.md):", ""] + [f"- {t}" for t in v["forbidden"]] + [""]
    L += ["## Visual", "", "### Colour", "", "Values come from the built design tokens (`assets/tokens/tokens.json`); the DTCG sources in `tokens/` are the truth.", ""]
    L += colour_table(doc) + [""]
    fs = fonts(doc)
    L += ["### Type", ""]
    L += [f"- {k}: `{val}`" for k, val in fs] if fs else ["The tokens define no font family."]
    L += [""]
    logos = logo_paths(project)
    L += ["### Mark", ""]
    L += [f"- `{p}`" for p in logos] if logos else ["No mark file exists yet under `assets/logo/`."]
    L += [""]
    if v["rules"]:
        L += ["### Rules", ""] + [f"- {r}" for r in v["rules"]] + [""]
    durs = [(k, val) for k, val in doc.get("other", {}).items() if k.startswith("duration.")]
    if durs:
        L += ["### Motion", ""] + [f"- {k}: {val}" for k, val in durs] + [""]
    L += ["## Governance", "", "### Naming", "", f"Name: {v['name']} (working slug `{v['slug']}`).", ""]
    ren = [ln for ln in v["renames"] if not re.fullmatch(r"\|[\s|:-]*\|?", ln.strip()) and not re.match(r"^\|\s*date\s*\|", ln.strip(), re.I)]
    if ren:
        L += ["Renames:", ""] + ["| date | from | to | why |", "|---|---|---|---|"] + [ln.strip() for ln in ren] + [""]
    legal = [r for r in facts if r.get("fact", "").lower().startswith("legal")]
    L += ["### Claims", "",
          "A claim about the brand is a row of FACTS.md. A status word (\"available\", \"launching\", \"in development\") needs a row that says so, with a date. "
          "No client, number, date or feature is added without one.", ""]
    if legal:
        L += ["Legal statements, verbatim:", ""] + [f"- {r['fact']}: {r.get('value', '')}" for r in legal] + [""]
    L += ["### Accessibility commitments", "",
          "Text and component pairs meet WCAG 2.2 AA (`brand-creator contrast`); logos are exempt and held to their own brand-rule targets. Ratios are computed from the tokens:", ""]
    L += pair_table(doc) + [""]
    L += ["### Approval", "", f"Edition {v['edition'] or 'not set'}: {state}{' on ' + date if date else ''}. A change to an approved edition opens the next edition, which needs a new approval.", ""]
    return "\n".join(L).rstrip("\n") + "\n"


# ---------------------------------------------------------------- DESIGN.md

def design_md(project: Path, *, primary: str | None = None) -> str:
    v = view(project)
    doc, _ = bookdata.tokens(project)
    light, dark = doc["modes"]["light"], doc["modes"]["dark"]
    roles = sorted(light)
    if primary and f"color.{primary}" not in light and primary not in light:
        fail(EXIT_USAGE, f"--primary {primary!r} is not a colour role of the tokens (roles: {', '.join(role(k) for k in roles)})")
    state, date = approval(v)
    L = ["---", "version: alpha", f"name: {yq(v['name'])}",
         f"description: {yq(v['name'] + ' design tokens, generated from the DTCG sources (edition ' + (v['edition'] or 'not set') + ', ' + state + ')')}", "colors:"]
    if primary:
        key = primary if primary in light else f"color.{primary}"
        L.append(f"  primary: {yq(mode_hex(doc, 'light', key))}")
    for k in roles:
        L.append(f"  {role(k)}: {yq(mode_hex(doc, 'light', k))}")
    for k in roles:
        if k in dark:
            L.append(f"  {role(k)}-dark: {yq(mode_hex(doc, 'dark', k))}")
    fs = fonts(doc)
    if fs:
        L.append("typography:")
        for k, val in fs:
            L += [f"  {k}:", f"    fontFamily: {yq(val)}"]
    dims = {k[10:]: str(val) for k, val in doc.get("other", {}).items() if k.startswith("dimension.")}
    spacing = {k: val for k, val in dims.items() if k.startswith("space")}
    rounded = {k: val for k, val in dims.items() if k.startswith(("radius", "rounded"))}
    if spacing:
        L.append("spacing:")
        L += [f"  {k}: {val}" for k, val in sorted(spacing.items())]
    if rounded:
        L.append("rounded:")
        L += [f"  {re.sub(r'^(radius|rounded)-?', '', k) or k}: {val}" for k, val in sorted(rounded.items())]
    comps = []
    for p in doc.get("pairs", []):
        if p.get("kind") == "ui-text":
            comps.append((f"{role(p['fg'])}-on-{role(p['bg'])}", role(p["fg"]), role(p["bg"]), p["fg"] in dark and p["bg"] in dark))
    if comps:
        L.append("components:")
        for name, fg, bg, has_dark in comps:
            L += [f"  {name}:", f"    backgroundColor: \"{{colors.{bg}}}\"", f"    textColor: \"{{colors.{fg}}}\""]
            if has_dark:
                L += [f"  {name}-dark:", f"    backgroundColor: \"{{colors.{bg}-dark}}\"", f"    textColor: \"{{colors.{fg}-dark}}\""]
    L += ["---", f"<!-- {GENERATED} -->", "", f"# {v['name']}", "", "## Overview", "",
          f"{v['name']} design tokens, edition {v['edition'] or 'not set'} ({state}{' ' + date if date else ''}). The DTCG sources in `tokens/` are the truth; "
          "this file is an agent-readable view of them and is regenerated, never edited.", ""]
    if v["register"]:
        L += [f"Register: {v['register']}.", ""]
    L += ["## Colors", "", f"{len(roles)} roles, each with a light and a dark value (`-dark`). Contrast pairs are checked by `brand-creator contrast`:", ""] + pair_table(doc) + [""]
    if fs:
        L += ["## Typography", "", "Families only: the tokens define no sizes or weights.", ""] + [f"- {k}: {val}" for k, val in fs] + [""]
    if spacing:
        L += ["## Layout", "", "Spacing steps come from the `dimension.space-*` tokens.", ""]
    if comps:
        L += ["## Components", "", "One entry per text pair that must meet WCAG AA 4.5:1, in light and dark.", ""]
    if v["rules"]:
        L += ["## Do's and Don'ts", ""] + [f"- {r}" for r in v["rules"]] + [""]
    return "\n".join(L).rstrip("\n") + "\n"


# ---------------------------------------------------------------- the applied skill

def skill_name(project: Path) -> str:
    slug = str(read_state(project).get("slug", "") or "")
    name = f"{slug}-brand"
    if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name) or len(name) > 64:
        fail(EXIT_USAGE, f"the project slug {slug!r} cannot make a skill name ({name!r}): lower-case letters, digits and single hyphens, 64 characters at most")
    if "claude" in name or "anthropic" in name:
        fail(EXIT_USAGE, f"a skill name may not contain 'claude' or 'anthropic' ({name!r}): rename the project slug first (`state --set slug=...`)")
    return name


def applied_skill_md(project: Path, template: str) -> str:
    v = view(project)
    doc, _ = bookdata.tokens(project)
    name = skill_name(project)
    state, date = approval(v)
    rules, src = qa_rules.load(project)
    ds = rules["downscale"]
    logos = logo_paths(project)
    fs = fonts(doc)
    sizes = [f"- {b.get('name', 'band')}: {'up to ' + str(b['max_px']) + ' px' if b.get('max_px') else 'larger sizes'} uses `{b.get('drawing', '')}`" for b in rules.get("bands", [])]
    never = ["Do not stretch, squash or rotate the mark.", "Do not recolour the mark outside the palette's roles, or put it on its own colour.",
             "Do not crowd the mark: keep its clear space free."] + [f"Never write: {t}." for t in v["forbidden"]]
    fill = {
        "name": name,
        "brand": v["name"],
        "description": (f"Applies the {v['name']} brand (colours, type, mark rules, claims) when making slides, documents, pages, posts or any other "
                        f"material for {v['name']}. Use it whenever {v['name']} material is created or reviewed."),
        "status": f"Edition {v['edition'] or 'not set'}: {state}{' on ' + date if date else ''}.",
        "colours": "\n".join(colour_table(doc)),
        "pairs": "\n".join(pair_table(doc)),
        "type": "\n".join([f"- {k}: `{val}`" for k, val in fs] if fs else ["The tokens define no font family: ask the owner before choosing one."]),
        "mark": "\n".join([f"- `../../../{p}`" for p in logos] if logos else ["No mark file exists yet under `assets/logo/`."]),
        "small": f"At {ds['accent_rule_max_size']} px and below the accent must hold a solid {ds['accent_min_px']} x {ds['accent_min_px']} px square "
                 f"({'qa/rules.json' if 'downscale.accent_min_px' in rules['_from_file'] else 'the plugin proposal until qa/rules.json sets it'}).\n\n" + ("\n".join(sizes) if sizes else ""),
        "never": "\n".join(f"- {t}" for t in never),
        "rules": "\n".join([f"- {r}" for r in v["rules"]] if v["rules"] else ["No G4 rules are recorded yet."]),
        "facts": "\n".join(facts_table(public_facts(project))),
        "generated": GENERATED,
    }
    out = template
    for k, val in fill.items():
        out = out.replace("{{" + k + "}}", val)
    left = re.findall(r"\{\{[a-z-]+\}\}", out)
    if left:
        fail(EXIT_USAGE, f"the applied-skill template has placeholders this version does not know: {', '.join(sorted(set(left)))}")
    return out
