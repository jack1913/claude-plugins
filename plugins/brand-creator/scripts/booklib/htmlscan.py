"""A small HTML scanner for the book tools (book_lint, patch, collapse). Standard library only.

It is not a browser: it tokenises tags with a regex that respects quoted attribute values, skips comments and the raw text of
<script> and <style>, and matches an element's end tag by counting the same tag name. That is enough for the books these tools
handle (generated by book.py, or hand-authored in the same plain style) and it keeps byte offsets, which patch and collapse need.
"""
from __future__ import annotations

import html as _html
import re
from dataclasses import dataclass

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}
RAW = {"script", "style"}
_TAG = re.compile(r"""<(/?)([A-Za-z][A-Za-z0-9:-]*)((?:[^>"']|"[^"]*"|'[^']*')*?)(/?)>""")
_COMMENT = re.compile(r"<!--.*?-->", re.S)
_ATTR = re.compile(r"""([^\s"'<>/=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?""")


@dataclass
class Tag:
    start: int
    end: int
    closing: bool
    name: str
    attrs_src: str
    selfclose: bool

    @property
    def attrs(self) -> dict[str, str]:
        return parse_attrs(self.attrs_src)

    @property
    def void(self) -> bool:
        return self.name in VOID or self.selfclose


def parse_attrs(src: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for m in _ATTR.finditer(src):
        v = m.group(2) if m.group(2) is not None else m.group(3) if m.group(3) is not None else m.group(4)
        out[m.group(1).lower()] = _html.unescape(v) if v is not None else ""
    return out


def tags(text: str):
    """Every tag in document order as a Tag. Comments and the bodies of <script> and <style> are skipped (their opening and
    closing tags are still yielded)."""
    i, n = 0, len(text)
    while i < n:
        lt = text.find("<", i)
        if lt < 0:
            return
        if text.startswith("<!--", lt):
            end = text.find("-->", lt + 4)
            i = n if end < 0 else end + 3
            continue
        m = _TAG.match(text, lt)
        if not m:
            i = lt + 1
            continue
        t = Tag(m.start(), m.end(), m.group(1) == "/", m.group(2).lower(), m.group(3), m.group(4) == "/")
        yield t
        i = m.end()
        if not t.closing and t.name in RAW and not t.selfclose:
            close = re.compile(r"</%s\s*>" % t.name, re.I).search(text, i)
            i = close.start() if close else n


def element_end(text: str, start_tag: Tag) -> int:
    """Index just after the end tag that closes the element opened by start_tag (a void element ends with its tag)."""
    if start_tag.void:
        return start_tag.end
    depth = 1
    for t in tags(text[start_tag.end:]):
        if t.name != start_tag.name or t.void:
            continue
        depth += -1 if t.closing else 1
        if depth == 0:
            return start_tag.end + t.end
    raise ValueError(f"<{start_tag.name}> opened at offset {start_tag.start} is never closed")


def elements(text: str, pred):
    """(start, end, Tag) of every element whose opening Tag satisfies pred(tag, attrs); nested matches are included."""
    for t in tags(text):
        if t.closing:
            continue
        a = t.attrs
        if pred(t, a):
            yield t.start, element_end(text, t), t


def strip_comments(text: str) -> str:
    return _COMMENT.sub("", text)


_SKIP_TEXT = re.compile(r"<(script|style)\b[^>]*>.*?</\1\s*>", re.I | re.S)
_ATTR_TEXT = ("alt", "title", "aria-label")


def visible_text(text: str, *, drop_svg: bool = False, with_attributes: bool = True) -> str:
    """The text a reader (or a screen reader) gets: tags, comments, <script>, <style> removed, entities decoded, whitespace
    collapsed. alt, title and aria-label values are appended on their own lines when with_attributes is set."""
    body = _COMMENT.sub(" ", text)
    body = _SKIP_TEXT.sub(" ", body)
    if drop_svg:
        body = re.sub(r"<svg\b.*?</svg\s*>", " ", body, flags=re.S | re.I)
    extra: list[str] = []
    if with_attributes:
        for t in tags(body):
            if t.closing:
                continue
            a = t.attrs
            for k in _ATTR_TEXT:
                if a.get(k):
                    extra.append(a[k])
    body = re.sub(r"<[^>]*>", " ", body)
    body = _html.unescape(body)
    out = re.sub(r"\s+", " ", body).strip()
    if extra:
        out += " \n" + " \n".join(re.sub(r"\s+", " ", x).strip() for x in extra)
    return out


def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1
