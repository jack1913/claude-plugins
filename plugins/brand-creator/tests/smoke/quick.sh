#!/usr/bin/env bash
# Quick-tier smoke test: a NON-software business (a synthetic neighbourhood bakery, brief in the owner's words) from `new` to `check`,
# on a machine that has none of the Apple tools and no git. Exits non-zero on any failure.
#
#   BRAND_CREATOR_DATA=<set-up data dir> tests/smoke/quick.sh          (tests/run-all.sh --smoke runs it after the Acme smoke)
#
# What it proves:
#   * every command runs with a PATH of symlinks that holds sips, iconutil, actool, xcrun and ictool nowhere (proved with `command -v` and
#     with the shim python's shutil.which), and with a git that is absent and a failing git shim in front that LOGS every call: the log must
#     stay empty. The project folder is outside any repository (no .git above it, GIT_CEILING_DIRECTORIES set).
#   * the path: new -> G0 recorded (tier quick, review_surface=local) -> the first board (board-lint, shots) -> tokens -> a mark generated by
#     code (px_lib, byte-identical on a second run) -> contrast -> logo sheet -> emit web -> emit social (Open Graph only, no GitHub or README images) -> emit profiles (avatar only) -> downscale -> book --init, book, book-lint -> check.
#   * the renderer question (resvg or pillow, sips being absent) is asked exactly once in the whole run (by prereq); the owner's answer
#     (pillow here) is recorded in BRAND-STATE.md, the Pillow path measures a PNG master and passes, and no later command asks again. A control
#     project proves what happens without an answer: exit 3, the question, nothing measured, no report; and that resvg measures an SVG.
#   * no Apple error, no platform-pack question and no package-registry check appears in the output of the Quick path.
#   * the packs of a higher tier refuse with exit 2 and the way up (state --set tier=full or tier=standard) and write nothing.
# The project lives in $QUICK_SMOKE_DIR (default $ACME_SMOKE_DIR-quick when that is set, else $TMPDIR/brand-creator-quick-smoke); a previous run is moved aside to <parent>/removed/, never deleted.
set -euo pipefail

HERE="$(cd -P "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -P "$HERE/../.." && pwd)"
FIX="$HERE/quick-bakery"   # the synthetic bakery: brief, facts, round 1 page, token sources, the mark generator
: "${BRAND_CREATOR_DATA:?set BRAND_CREATOR_DATA to a data directory prepared by: brand-creator --data <dir> setup --yes}"
SMOKE="${QUICK_SMOKE_DIR:-${ACME_SMOKE_DIR:+$ACME_SMOKE_DIR-quick}}"   # next to the Acme smoke folder when that one is set (one scratch place per run)
SMOKE="${SMOKE:-${TMPDIR:-/tmp}/brand-creator-quick-smoke}"
export BRAND_CREATOR_TODAY="${BRAND_CREATOR_TODAY:-2026-10-17}"

step() { printf '\n== %s\n' "$*"; }
ok()   { printf '   ok: %s\n' "$*"; }
die()  { printf 'QUICK SMOKE FAILED: %s\n' "$*" >&2; exit 1; }
png_size() { python3 -c "import struct,sys;d=open(sys.argv[1],'rb').read(24);assert d[:8]==b'\x89PNG\r\n\x1a\n';print(*struct.unpack('>II',d[16:24]))" "$1"; }
expect_size() { local got; got="$(png_size "$1")"; [ "$got" = "$2 $3" ] || die "$1 is $got, expected $2 $3"; ok "$(basename "$1") is $2x$3"; }
expect_file() { [ -s "$1" ] || die "missing or empty: $1"; ok "$1"; }

# ---------------------------------------------------------------------------------------------------------------- the environment
step "scaffold folder $SMOKE"
if [ -e "$SMOKE" ]; then
  mkdir -p "$(dirname "$SMOKE")/removed"
  mv "$SMOKE" "$(dirname "$SMOKE")/removed/$(basename "$SMOKE")-$(date +%Y%m%d%H%M%S)-$$"
  ok "previous run moved aside"
fi
mkdir -p "$SMOKE"
SMOKE="$(cd -P "$SMOKE" && pwd)"
SHIM="$SMOKE/shim"; GITSHIM="$SMOKE/gitshim"; WORK="$SMOKE/work"; CTRL="$SMOKE/control"
LOGS="$SMOKE/logs"; CLOGS="$SMOKE/logs-control"; GIT_LOG="$SMOKE/git-calls.log"
mkdir -p "$SHIM" "$GITSHIM" "$WORK" "$CTRL" "$LOGS" "$CLOGS"
REAL_BASH="$(type -P bash)"

step "a PATH without sips, iconutil, actool, xcrun, ictool and git"
# Symlinks to every tool the Quick path needs, and to nothing else (npm and npx are two-line wrappers, see below).
for t in bash env dirname basename readlink mkdir cat sed awk grep sort ls head tail tr date cp mv uname mktemp cmp wc ln chmod id stat find xargs tee touch cut uniq diff \
         uv node python3 resvg; do
  p="$(type -P "$t")" || die "a tool the Quick path needs is missing on this machine: $t"
  ln -s "$p" "$SHIM/$t"
done
for t in npm npx; do   # npm and npx are Node scripts that find their own files relative to themselves: run the CLI file with the shim's node
  if p="$(type -P "$t")"; then
    cli="$(dirname "$p")/../lib/node_modules/npm/bin/$t-cli.js"
    if [ -f "$cli" ]; then printf '#!/bin/sh\nexec "%s" "%s" "$@"\n' "$SHIM/node" "$cli" >"$SHIM/$t"; else printf '#!/bin/sh\nexec "%s" "$@"\n' "$p" >"$SHIM/$t"; fi
    chmod +x "$SHIM/$t"
  fi
done
if p="$(type -P claude)"; then ln -s "$p" "$SHIM/claude"; fi   # prereq reads its version; it is not an Apple tool
APPLE_TOOLS=(sips iconutil actool xcrun ictool)
for t in "${APPLE_TOOLS[@]}" git; do
  [ ! -e "$SHIM/$t" ] || die "$t is in the shim directory"
  if env PATH="$SHIM" "$REAL_BASH" -c "command -v $t" >/dev/null 2>&1; then die "command -v $t finds it on the shim PATH"; fi
  real="$(type -P "$t" || true)"
  ok "command -v $t finds nothing on the shim PATH${real:+ (this machine has $real; it is hidden)}"
done
env PATH="$SHIM" python3 - "${APPLE_TOOLS[@]}" git <<'PY' || die "the shim python finds a hidden tool"
import shutil, sys
found = {t: shutil.which(t) for t in sys.argv[1:] if shutil.which(t)}
assert not found, found
print("   ok: shutil.which finds none of", ", ".join(sys.argv[1:]))
PY
# git: absent from the shim, and a failing shim first on PATH that logs every call. The log must stay empty.
cat >"$GITSHIM/git" <<EOF
#!/bin/sh
printf '%s git %s (cwd %s)\n' "\$(date +%H:%M:%S)" "\$*" "\$(pwd)" >>"$GIT_LOG"
echo "git was called during the Quick-tier smoke test, which must not use git: git \$*" >&2
exit 127
EOF
chmod +x "$GITSHIM/git"
[ "$(env PATH="$GITSHIM:$SHIM" "$REAL_BASH" -c 'command -v git')" = "$GITSHIM/git" ] || die "the git shim is not first on PATH"
ok "a failing git shim is first on PATH and logs to $GIT_LOG"
# the project folder is outside any repository
python3 - "$SMOKE" <<'PY' || die "the smoke folder is inside a repository (a .git exists above it)"
import sys
from pathlib import Path
p = Path(sys.argv[1]).resolve()
hit = [str(a) for a in [p, *p.parents] if (a / ".git").exists()]
assert not hit, hit
print("   ok: no .git in", p, "or above it")
PY
CEIL="$(dirname "$SMOKE")"

# bcq: brand-creator with the stripped PATH, the git shim and the git ceiling. q NAME args...: run it, keep its output in $LOGS/NAME.log, set RC.
bcq() { env PATH="$GITSHIM:$SHIM" GIT_CEILING_DIRECTORIES="$CEIL" "$ROOT/bin/brand-creator" --data "$BRAND_CREATOR_DATA" "$@"; }
RC=0
q()   { local n="$1"; shift; RC=0; bcq "$@" >"$LOGS/$n.log" 2>&1 || RC=$?; cat "$LOGS/$n.log"; }
qok() { local n="$1"; shift; q "$n" "$@"; [ "$RC" = 0 ] || die "$n: brand-creator $* exited $RC"; }
qrc() { local n="$1" want="$2"; shift 2; q "$n" "$@"; [ "$RC" = "$want" ] || die "$n: brand-creator $* exited $RC, expected $want"; }
cq()  { local n="$1"; shift; RC=0; bcq "$@" >"$CLOGS/$n.log" 2>&1 || RC=$?; cat "$CLOGS/$n.log"; }   # the control project's runs
sh_() { env PATH="$GITSHIM:$SHIM" GIT_CEILING_DIRECTORIES="$CEIL" "$@"; }

# ------------------------------------------------------------------------------------------------------------------- prereq (the question)
step "prereq --for quick: the renderer question, asked here and nowhere else"
qok prereq prereq --for quick
grep -q "^WARN     sips" "$LOGS/prereq.log" || die "prereq did not report the missing downscaler"
[ "$(grep -c -- '--renderer=resvg|pillow choice' "$LOGS/prereq.log")" = 1 ] || die "prereq must ask the renderer question exactly once"
grep -q "nothing blocks this scope" "$LOGS/prereq.log" || die "prereq --for quick is blocked"
ok "prereq: sips missing is a WARN that carries the question once, and nothing blocks the Quick tier"

# ------------------------------------------------------------------------------------------------------------------ new, brief and G0
step "new: a Quick-tier project for a bakery (the owner's brief in their words)"
qok new new marlow-lane --name "Marlow Lane Bakery" --tier quick --root "$WORK"
P="$WORK/marlow-lane"
expect_file "$P/BRAND-STATE.md"; expect_file "$P/FACTS.md"; expect_file "$P/brief/BRIEF.md"
[ ! -e "$P/.git" ] || die "new created a .git in the project"
cp "$FIX/brief.md" "$P/brief/BRIEF.md"; cp "$FIX/facts.md" "$P/FACTS.md"
grep -q "the neighbours queue out of the door" "$P/brief/BRIEF.md" || die "the brief does not carry the owner's words"

step "G0: scope recorded (tier quick, generated mark, local review surface)"
qok state-set state --project "$P" --set review_surface=local --set content_languages=en --set language=en --set mark_source=generated --set phase=P3
qok g0 state --project "$P" --record G0 "quick tier, generated mark, name decided, review on this machine"
qok state state --project "$P" --json
python3 - "$LOGS/state.log" <<'PY' || die "BRAND-STATE.md does not hold the G0 scope"
import json, sys
st = json.load(open(sys.argv[1]))
fm = st["state"]
assert fm["tier"] == "quick", fm["tier"]
assert fm["review_surface"] == "local", fm["review_surface"]
assert fm["mark_source"] == "generated" and fm["architecture"] == "standalone"
assert "quick tier" in str(fm["gates"]["G0"]), fm["gates"]
print("   ok: tier quick, architecture standalone, mark_source generated, review_surface local, G0 recorded")
PY
qok require-g0 state --project "$P" --require G0
qrc require-g3-early 1 state --project "$P" --require G3
ok "G3 is not recorded yet, so the emitters would refuse"

# ------------------------------------------------------------------------------------------------------------------ the first board
step "round 1: the first board (three directions), board-lint, four-view shots"
mkdir -p "$P/rounds/r1"
cp "$FIX/board.html" "$P/rounds/r1/board.html"
qok board-lint board-lint rounds/r1/board.html --project "$P"
qok shot shot rounds/r1/board.html --project "$P"
python3 - "$P/assets/_checks/shot.json" "$P/assets/_checks/board-lint.json" <<'PY' || die "shot or board-lint report is not what the Quick tier needs"
import json, sys
rep = json.load(open(sys.argv[1]))
assert rep["status"] == "pass", rep["status"]
assert [r["id"] for r in rep["results"]] == ["view:1440-light", "view:1440-dark", "view:390-light", "view:390-dark"]
assert all(r["slices"] for r in rep["results"])
bl = json.load(open(sys.argv[2]))
assert bl["status"] == "pass", bl["status"]
print("   ok: board-lint pass, 4 views with slices")
PY
qok g2 state --project "$P" --record G2 "picked Hearth (A)"
qok g3 state --project "$P" --record G3 "approved r1 (smoke)"
qok set-direction state --project "$P" --set canonical_direction=Hearth --set phase=P7

# --------------------------------------------------------------------------------------------------------------------- tokens and mark
step "tokens: DTCG sources to css, json, swift, android, colorsets (hex fallbacks computed)"
mkdir -p "$P/tokens" "$P/assets/logo" "$P/tools"
cp "$FIX"/tokens/*.tokens.json "$P/tokens/"
qok tokens-fix tokens --project "$P" --fix-hex
qok tokens tokens --project "$P"
for f in tokens.css tokens.json Colors.xcassets/Contents.json; do expect_file "$P/assets/tokens/$f"; done
qok tokens-check tokens --project "$P" --check

step "the mark: generated by code (px_lib), byte-identical on a second run"
cp "$FIX/tools/loaf_mark.py" "$P/tools/"
ROOT_LIB="$(bcq root)"
( cd "$P" && sh_ BRAND_CREATOR_ROOT="$ROOT_LIB" python3 tools/loaf_mark.py ) | sed 's/^/   /'
for f in mark.svg mark-dark.svg mark-master.png; do expect_file "$P/assets/logo/$f"; done
SUMS="$(cd "$P/assets/logo" && cksum mark.svg mark-dark.svg mark-master.png)"
( cd "$P" && sh_ BRAND_CREATOR_ROOT="$ROOT_LIB" python3 tools/loaf_mark.py ) >/dev/null
[ "$(cd "$P/assets/logo" && cksum mark.svg mark-dark.svg mark-master.png)" = "$SUMS" ] || die "the mark generator is not deterministic"
expect_size "$P/assets/logo/mark-master.png" 1000 1000
ok "the mark is the same bytes on a second run"

# ------------------------------------------------------------------------------------------------------------------- contrast, sheet
step "contrast (WCAG 2.2 AA pairs, brand rules, touching pairs read from the logo raster)"
cp "$FIX/tokens/exceptions.json" "$P/tokens/exceptions.json"
qok contrast contrast --project "$P"
expect_file "$P/assets/_checks/contrast.json"

step "logo sheet"
qok logo-sheet logo-sheet --project "$P"
expect_file "$P/assets/_checks/logo-sheet.png"

# ------------------------------------------------------------------------------------------------------------------------ emitters
step "emit web (favicon set, apple-touch icon, PWA icons, head snippet)"
qok emit-web emit web --project "$P"
expect_size "$P/assets/web/apple-touch-icon.png" 180 180
expect_size "$P/assets/web/icons/icon-192.png" 192 192
expect_size "$P/assets/web/icons/icon-512.png" 512 512
expect_size "$P/assets/web/icons/maskable-512.png" 512 512
expect_file "$P/assets/web/favicon.ico"; expect_file "$P/assets/web/icon.svg"; expect_file "$P/assets/web/site.webmanifest"; expect_file "$P/assets/web/head.html"
qok emit-web-again emit web --project "$P"
grep -q "0 written" "$LOGS/emit-web-again.log" || die "a second emit web wrote files"

step "emit social: the Open Graph card only (a bakery lists no code repository, so no GitHub preview and no README headers)"
qok emit-social emit social --project "$P" --tagline "Baked before you were up"
OG="$(ls "$P"/assets/social/og-1200x630-*.png | head -n 1)"
expect_size "$OG" 1200 630
[ ! -e "$P/assets/social/github-social-1280x640.png" ] && [ ! -e "$P/assets/social/readme-header-light.png" ] && [ ! -e "$P/assets/social/readme-header-dark.png" ] \
  || die "emit social wrote a GitHub or README image for a business with no code repository"
grep -q "no code repository is listed" "$LOGS/emit-social.log" || die "emit social did not say why it skipped the GitHub and README images"
ok "no GitHub social preview and no README header, and the run says why"

step "emit profiles in the Quick tier: the circle-safe avatar (400, 800), no banners"
qok emit-profiles emit profiles --project "$P"
expect_size "$P/assets/profiles/avatar-400.png" 400 400; expect_size "$P/assets/profiles/avatar-800.png" 800 800
[ "$(ls "$P"/assets/profiles/*.png | wc -l | tr -d ' ')" = 2 ] || die "emit profiles in the Quick tier wrote more than the two avatars"
grep -q "no banners in the Quick tier" "$LOGS/emit-profiles.log" || die "emit profiles did not say that the banners are Standard"
ok "two avatars inside the safe circle; the banners are named as the Standard tier's"

# ------------------------------------------------------------------------------------------ the owner's answer, and the Pillow path
step "the owner chooses Pillow: recorded once, the PNG master is measured"
[ "$(bcq state --project "$P" --get renderer)" = "resvg" ] || die "BRAND-STATE.md already holds an opt-in before the owner chose"
qok downscale-record downscale --project "$P" --source assets/logo/mark-master.png --renderer=pillow --record-renderer
grep -q "recorded in BRAND-STATE.md: renderer: pillow (opted in 2026-10-17)" "$LOGS/downscale-record.log" || die "the opt-in was not recorded"
[ "$(bcq state --project "$P" --get renderer)" = "pillow (opted in 2026-10-17)" ] || die "BRAND-STATE.md does not hold the recorded opt-in"
qok downscale downscale --project "$P" --source assets/logo/mark-master.png
if grep -q -- "--renderer=" "$LOGS/downscale.log" && grep -q "no renderer opt-in" "$LOGS/downscale.log"; then die "a later downscale asked the renderer question again"; fi
python3 - "$P" <<'PY' || die "the Pillow downscale report is not a pass measured by Pillow"
import json, sys
from pathlib import Path
files = sorted((Path(sys.argv[1]) / "assets/_checks/downscale").glob("*.json"))
assert len(files) == 1, files
rep = json.load(open(files[0]))
assert rep["status"] == "pass", (rep["status"], [r for r in rep["results"] if r["status"] != "pass"])
assert "pillow" in rep["renderer"].lower(), rep["renderer"]
sizes = [r for r in rep["results"] if r["id"].startswith("size:") or r["id"].startswith("rule:")]
print(f"   ok: {rep['renderer']}; {len(rep['results'])} rows, status pass")
PY
qrc downscale-svg 3 downscale --project "$P" --source assets/logo/mark.svg --renderer=pillow
grep -qi "pillow" "$LOGS/downscale-svg.log" && grep -qi "svg" "$LOGS/downscale-svg.log" || die "pillow on an SVG source must say it cannot rasterise SVG"
ok "Pillow asked to rasterise an SVG exits 3 and says so (no silent fallback)"

# ------------------------------------------------------------------------------------------------------- the short guide (G5)
step "the short guide: Quick chapters only, filled with plain text, built, verified, linted"
python3 - "$P/BRAND-STATE.md" <<'PY' || die "the rules list of BRAND-STATE.md could not be written"
import sys
t = open(sys.argv[1]).read()
old = "- (rule) (...)"
assert old in t, "the rules placeholder is not in BRAND-STATE.md"
open(sys.argv[1], "w").write(t.replace(old, "- (rule) the cream ground stays behind the loaf mark on every bag and sign (proposal)", 1))
PY
qok book-init book --init --project "$P"
python3 - "$P" <<'PY' || die "the Quick short guide holds the wrong chapters, or a slot could not be filled"
import glob, os, re, sys
p = sys.argv[1]
names = sorted(os.path.basename(f)[:-3].split("-", 1)[-1] for f in glob.glob(p + "/book/chapters/*.md"))
want = {"idea", "mark", "colour", "files", "changing"}
wordmark = any(os.path.exists(p + "/assets/logo/" + n) for n in ("wordmark.svg", "lockup.svg"))
if wordmark:
    want.add("wordmark")
assert set(names) == want, (names, sorted(want))
n = 0
for f in glob.glob(p + "/book/chapters/*.md"):
    t = open(f).read()
    t, k = re.subn(r"\[\[fill:.*?\]\](?!\])", "The loaf mark sits on the paper bag and the shop sign, always on the cream ground.", t, flags=re.S)
    n += k
    open(f, "w").write(t)
assert n >= 5, n
print(f"   ok: chapters {sorted(want)}; {n} slots filled")
PY
qok book book --project "$P"
expect_file "$P/book.html"
qok book-verify book --verify --project "$P"
qok book-lint book-lint --self-consistency --project "$P"
ok "short guide built, verified and linted"

# --------------------------------------------------------------------------------------------------------------------------- check
step "check: every gate that applies to the Quick tier"
q check check --project "$P"
[ "$RC" = 0 ] || die "check exited $RC on a finished Quick-tier project"
ok "check exits 0"

# ----------------------------------------------------------------------------- the name question is domains only, never a registry
step "names --plan for a bakery (consumer profile): domains and manual links, no package registry"
qok names-plan names marlowlane --project "$P" --profile consumer --region GB --plan
grep -qi "rdap\|domain" "$LOGS/names-plan.log" || die "the plan does not list the domain sources"

# ------------------------------------------------------------------------------------------------------------ higher-tier packs refuse
step "packs of a higher tier refuse with exit 2 and the way up, and write nothing"
for pack in android chrome-ext msix; do
  qrc "refuse-$pack" 2 emit "$pack" --project "$P"
  grep -q "state --set tier=full" "$LOGS/refuse-$pack.log" || die "emit $pack in the Quick tier must name the way up (tier=full)"
  [ ! -e "$P/assets/$pack" ] || die "emit $pack wrote files in the Quick tier"
  ok "emit $pack: exit 2, names 'state --set tier=full', nothing written"
done
qrc refuse-presskit 2 emit presskit --project "$P"
qrc refuse-print 2 emit print --project "$P" --region EU
qrc refuse-posts 2 emit social --project "$P" --posts --tagline "Baked before you were up"
for n in presskit print posts; do
  grep -q "state --set tier=standard" "$LOGS/refuse-$n.log" || die "emit $n in the Quick tier must name the way up (tier=standard)"
  ok "emit $n: exit 2, names 'state --set tier=standard'"
done
[ ! -e "$P/assets/print" ] && [ ! -e "$P/assets/presskit" ] && [ ! -e "$P/assets/social/posts" ] || die "a Standard-tier pack wrote files in the Quick tier"
for t in presskit print android chrome-ext msix; do
  [ ! -e "$P/assets/_checks/emit-$t.json" ] || die "the refused emit $t left a report behind (a run that never started)"
done
ok "a refusal leaves no report behind"
qok check-after-refusals check --project "$P"
ok "check still exits 0 after the refusals"

# --------------------------------------------------------------------------------------------------- control: no answer to the question
step "control project: without the owner's answer the downscale check stops (exit 3), asks, and measures nothing; resvg measures an SVG"
cqok() { local n="$1"; shift; cq "$n" "$@"; [ "$RC" = 0 ] || die "$n: exit $RC"; }
cqok c-new new control --name "Control" --tier quick --root "$CTRL"
C="$CTRL/control"
mkdir -p "$C/assets/logo"; cp "$P"/assets/logo/mark.svg "$P"/assets/logo/mark-master.png "$C/assets/logo/"
cq c-ask downscale --project "$C" --source assets/logo/mark-master.png --accent '#b4521e' --ground '#f8f0e3'
[ "$RC" = 3 ] || die "downscale without an opt-in must exit 3 (exit $RC)"
grep -q "no renderer opt-in is recorded" "$CLOGS/c-ask.log" && grep -q -- "--renderer=pillow" "$CLOGS/c-ask.log" && grep -q "Nothing was measured" "$CLOGS/c-ask.log" || die "the refusal does not ask the question"
[ ! -e "$C/assets/_checks/downscale" ] || die "a report was written although nothing was measured"
ok "exit 3, the question is asked, no report"
cq c-resvg downscale --project "$C" --source assets/logo/mark.svg --renderer=resvg --record-renderer --accent '#b4521e' --ground '#f8f0e3'
[ "$RC" = 0 ] || die "resvg on the SVG master failed (exit $RC)"
[ "$(bcq state --project "$C" --get renderer)" = "resvg (opted in 2026-10-17)" ] || die "the resvg opt-in was not recorded"
ok "resvg measures the SVG master and records its opt-in"
cq c-apple emit apple --project "$C"
[ "$RC" = 3 ] || die "emit apple without the Apple tools must exit 3 (exit $RC)"
[ -z "$(ls "$C/assets" 2>/dev/null | grep -x apple || true)" ] || die "emit apple wrote files without Xcode"
ok "emit apple, asked for by name with the Apple tools hidden, exits 3 and writes nothing"

# ------------------------------------------------------------------------------------------------------------ the whole run, read back
step "the whole Quick run, read back: no git call, one renderer question, no Apple error, no platform-pack question, no registry check"
[ ! -s "$GIT_LOG" ] || die "git was called: $(cat "$GIT_LOG")"
ok "the git shim's log is empty: nothing called git"
[ ! -e "$P/.git" ] && [ ! -e "$C/.git" ] || die "a .git appeared in a project"
python3 - "$LOGS" "$CLOGS" <<'PY' || die "the output of the Quick path breaks a rule above"
import re, sys
from pathlib import Path
logs, clogs = Path(sys.argv[1]), Path(sys.argv[2])
main = {f.stem: f.read_text(encoding="utf-8", errors="replace") for f in sorted(logs.glob("*.log"))}
refusals = {k for k in main if k.startswith("refuse-") or k in ("downscale-svg", "require-g3-early")}   # runs that are supposed to refuse
quick = {k: v for k, v in main.items() if k not in refusals}
question = "--renderer=resvg|pillow choice"
asked = {k: v.count(question) for k, v in main.items() if question in v}
assert asked == {"prereq": 1}, f"the renderer question must be asked once, by prereq: {asked}"
bad = []
for k, text in quick.items():
    for pat, what in ((r"xcrun|actool|iconutil|ictool|xcode|assetutil|xcode-select", "an Apple tool"),
                      (r"platform pack|deployment target|which platforms|INVENTORY\.md", "a platform-pack question"),
                      (r"registry\.npmjs|npmjs\.com|pypi\.org|crates\.io|hub\.docker|formulae\.brew|package registr|npm view", "a package-registry check"),
                      (r"Traceback|command not found|No such file or directory|not a git repository|fatal:", "an error trace")):
        m = re.search(pat, text, re.I)
        if m:
            bad.append(f"{k}: {what}: {m.group(0)!r}")
    if k != "prereq" and re.search(r"\bsips\b", text, re.I):
